import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const websiteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = path.resolve(websiteRoot, '..');
const [sourceArgument, outputArgument, casesArgument, ...extraArguments] = process.argv.slice(2);

const customArguments = [sourceArgument, outputArgument, casesArgument];
if (
  extraArguments.length > 0
  || (customArguments.some((value) => value !== undefined)
    && customArguments.some((value) => value === undefined))
) {
  throw new Error(
    'sync-factorial expects source, output, and example-cases paths, or none',
  );
}

const sourceReference = sourceArgument ?? 'examples/functions/factorial.jz';
const sourcePath = sourceArgument ?? path.join(repositoryRoot, sourceReference);
const outputPath = outputArgument ?? path.join(websiteRoot, 'src/generated/factorial.ts');
const casesPath = casesArgument ?? path.join(repositoryRoot, 'scripts/example-cases.tsv');
const [source, cases] = await Promise.all([
  readFile(sourcePath, 'utf8'),
  readFile(casesPath, 'utf8'),
]);

const lines = cases.split(/\r?\n/);
if (lines[0] !== 'name\tsources\texpected\targs') {
  throw new Error('example-cases.tsv has an unexpected header');
}
const factorialCases = lines
  .slice(1)
  .filter(Boolean)
  .map((line) => line.split('\t'))
  .filter(([name]) => name === 'factorial');
if (factorialCases.length !== 1 || factorialCases[0].length !== 4) {
  throw new Error('example-cases.tsv must contain exactly one factorial case');
}
const [, rawSources, expectedOutput, args] = factorialCases[0];
if (
  !rawSources.split(',').includes(sourceReference)
  || args !== `--run ${sourceReference}`
  || expectedOutput.length === 0
) {
  throw new Error('factorial case does not execute the synchronized source');
}

const finalSourceLine = source.trimEnd().split(/\r?\n/).at(-1)?.trim() ?? '';
if (!finalSourceLine.endsWith('.') || finalSourceLine === '.') {
  throw new Error('factorial source must end with the displayed invocation');
}
const invocation = finalSourceLine.slice(0, -1).trim();
const generated =
  '// Generated by website/scripts/sync-factorial.mjs. Do not edit.\n' +
  `export const factorialSource = ${JSON.stringify(source)};\n` +
  `export const factorialInvocation = ${JSON.stringify(invocation)};\n` +
  `export const factorialExpectedOutput = ${JSON.stringify(expectedOutput)};\n`;

await mkdir(path.dirname(outputPath), {recursive: true});
await writeFile(outputPath, generated, 'utf8');
