import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const websiteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = path.resolve(websiteRoot, '..');
const [sourceArgument, outputArgument] = process.argv.slice(2);

if ((sourceArgument === undefined) !== (outputArgument === undefined)) {
  throw new Error('sync-factorial expects both source and output paths, or neither');
}

const sourcePath = sourceArgument ?? path.join(repositoryRoot, 'examples/functions/factorial.jz');
const outputPath = outputArgument ?? path.join(websiteRoot, 'src/generated/factorial.ts');
const source = await readFile(sourcePath, 'utf8');
const generated =
  '// Generated by website/scripts/sync-factorial.mjs. Do not edit.\n' +
  `export const factorialSource = ${JSON.stringify(source)};\n`;

await mkdir(path.dirname(outputPath), {recursive: true});
await writeFile(outputPath, generated, 'utf8');
