import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import test from 'node:test';

const websiteRoot = path.resolve(import.meta.dirname, '..');
const repositoryRoot = path.resolve(websiteRoot, '..');

function read(relativePath) {
  return readFileSync(path.join(repositoryRoot, relativePath), 'utf8');
}

function tokenScopes(tokens) {
  return new Set(
    tokens.flatMap((line) =>
      line.flatMap((token) =>
        (token.explanation ?? []).flatMap((explanation) =>
          explanation.scopes.map(({scopeName}) => scopeName),
        ),
      ),
    ),
  );
}

test('factorial sync emits source, invocation, and compiler-checked output', () => {
  const fixture = mkdtempSync(path.join(tmpdir(), 'jazz-factorial-'));
  try {
    const source = path.join(fixture, 'factorial.jz');
    const output = path.join(fixture, 'factorial.ts');
    const cases = path.join(fixture, 'example-cases.tsv');
    const contents = (
      'factorial :: Int -> Int.\n'
      + 'factorial = "\\n".\n'
      + 'factorial 7.\n'
    );
    writeFileSync(source, contents);
    writeFileSync(
      cases,
      'name\tsources\texpected\targs\n'
        + `factorial\t${source}\t5040\t--run ${source}\n`,
    );

    execFileSync(process.execPath, [
      path.join(websiteRoot, 'scripts/sync-factorial.mjs'),
      source,
      output,
      cases,
    ]);

    assert.equal(
      readFileSync(output, 'utf8'),
      '// Generated by website/scripts/sync-factorial.mjs. Do not edit.\n' +
        `export const factorialSource = ${JSON.stringify(contents)};\n` +
        'export const factorialInvocation = "factorial 7";\n' +
        'export const factorialExpectedOutput = "5040";\n',
    );
  } finally {
    rmSync(fixture, {recursive: true, force: true});
  }
});

